import { readFileSync, renameSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { basename, extname } from "node:path";

/** Project documents are small JSON files; refuse anything absurd. */
export const MAX_PROJECT_BYTES = 5 * 1024 * 1024;
/** Spreadsheets can be large, but the parser holds whole workbooks in memory. */
export const MAX_SPREADSHEET_BYTES = 25 * 1024 * 1024;

export const PROJECT_EXTENSIONS = ["whatif", "json"];
export const SPREADSHEET_EXTENSIONS = ["xlsx", "xls", "csv"];

export interface FilePayload {
  filePath: string;
  name: string;
  bytes: Uint8Array;
}

export type DroppedFileKind = "project" | "spreadsheet" | null;

/** Extension-only classification; size and file type still go through read*. */
export function classifyFile(filePath: string): DroppedFileKind {
  const extension = extname(filePath).slice(1).toLowerCase();
  if (PROJECT_EXTENSIONS.includes(extension)) return "project";
  if (SPREADSHEET_EXTENSIONS.includes(extension)) return "spreadsheet";
  return null;
}

function assertReadable(filePath: string, maxBytes: number, allowed: string[]): void {
  const extension = extname(filePath).slice(1).toLowerCase();
  if (!allowed.includes(extension)) {
    throw new Error(`不支持的文件类型：.${extension || "(无扩展名)"}`);
  }
  const stats = statSync(filePath);
  if (!stats.isFile()) throw new Error("所选路径不是文件");
  if (stats.size > maxBytes) {
    throw new Error(`文件过大（${Math.round(stats.size / 1024 / 1024)}MB），上限 ${Math.round(maxBytes / 1024 / 1024)}MB`);
  }
}

/** Read a project document from disk as UTF-8 text. */
export function readProjectFile(filePath: string): FilePayload {
  assertReadable(filePath, MAX_PROJECT_BYTES, PROJECT_EXTENSIONS);
  const bytes = readFileSync(filePath);
  return { filePath, name: basename(filePath), bytes: new Uint8Array(bytes) };
}

/** Read an Excel/CSV file as raw bytes; parsing happens in the renderer. */
export function readSpreadsheetFile(filePath: string): FilePayload {
  assertReadable(filePath, MAX_SPREADSHEET_BYTES, SPREADSHEET_EXTENSIONS);
  const bytes = readFileSync(filePath);
  return { filePath, name: basename(filePath), bytes: new Uint8Array(bytes) };
}

/**
 * Write renderer-generated bytes to a path the user picked in a save dialog.
 *
 * Write to a sibling temp file and rename it into place: a crash or power loss
 * then leaves either the old file or the new one, never a truncated document.
 */
export function writeFileBytes(filePath: string, data: Uint8Array): void {
  const tempPath = `${filePath}.${process.pid}.${Date.now()}.tmp`;
  try {
    writeFileSync(tempPath, Buffer.from(data), { mode: 0o600 });
    renameSync(tempPath, filePath);
  } catch (error) {
    try {
      unlinkSync(tempPath);
    } catch {
      // The temp file may never have been created; the original error matters.
    }
    throw error;
  }
}
